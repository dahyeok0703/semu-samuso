export const KNOWN_HOLIDAY_YEARS = Object.keys(KOREAN_PUBLIC_HOLIDAYS).map(Number);

/** Holiday set for a single year ("YYYY-MM-DD"). Unknown years → empty set. */
export function getHolidaySet(year: number): Set<string> {
  return new Set(KOREAN_PUBLIC_HOLIDAYS[year] ?? []);
}

/** Merged holiday set spanning several years (deadlines can roll into year+1). */
export function getHolidaySetForYears(years: number[]): Set<string> {
  const set = new Set<string>();
  for (const y of years) {
    for (const d of KOREAN_PUBLIC_HOLIDAYS[y] ?? []) set.add(d);
  }
  return set;
}
